// Usage: node build.mjs
// Concatenates components/**/*.jsx into _ds_bundle.jsx (loaded by cards through Babel standalone)
// and regenerates _ds_manifest.json from the files on disk. No dependencies.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const NAMESPACE = 'PersonaFiveRoyalDS';
const GROUPS = ['controls', 'navigation', 'surfaces', 'feedback', 'brand'];
const ORDER_FIRST = ['RansomTitle']; // others import it

const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]);
const rel = (p) => relative(root, p).replaceAll('\\', '/');

const components = GROUPS.flatMap((g) =>
  readdirSync(join(root, 'components', g)).filter((f) => f.endsWith('.jsx')).map((f) => ({
    name: f.replace('.jsx', ''), sourcePath: `components/${g}/${f}`,
  })),
).sort((a, b) => (ORDER_FIRST.includes(b.name) ? 1 : 0) - (ORDER_FIRST.includes(a.name) ? 1 : 0));

let out = `/* generated by build.mjs: do not edit. Namespace: window.${NAMESPACE} */\n`;
out += 'const { useState, useEffect, useLayoutEffect, useMemo, useRef, useId } = React;\n';
for (const c of components) {
  const src = readFileSync(join(root, c.sourcePath), 'utf8')
    .replace(/^import .+ from ['"](react|\.\/[^'"]+)['"];?\s*$/gm, '')
    .replace(/^export (function|const)/gm, '$1');
  out += `\n/* ${c.sourcePath} */\n${src}`;
}
out += `\nwindow.${NAMESPACE} = { ${components.map((c) => c.name).join(', ')} };\n`;
writeFileSync(join(root, '_ds_bundle.jsx'), out);

const cardAttr = (file) => {
  const m = readFileSync(file, 'utf8').match(/<!--\s*@dsCard\s+([^>]*?)-->/);
  if (!m) return null;
  return Object.fromEntries([...m[1].matchAll(/(\w+)="([^"]*)"/g)].map((x) => [x[1], x[2]]));
};
const cards = [
  ...(existsSync(join(root, 'guidelines')) ? walk(join(root, 'guidelines')).filter((f) => f.endsWith('.html')) : []),
  ...walk(join(root, 'components')).filter((f) => f.endsWith('.card.html')),
].map((f) => ({ path: rel(f), ...cardAttr(f) })).filter((c) => c.name);

const tokenFiles = ['colors', 'typography', 'spacing', 'effects'].map((n) => `tokens/${n}.css`);
const kindOf = (name, file) =>
  file.endsWith('colors.css') ? 'color' : name.startsWith('--space') || name.startsWith('--container') || name.startsWith('--hud') || name.startsWith('--menu-gap') || name.startsWith('--stagger') ? 'spacing'
    : name.startsWith('--radius') ? 'radius' : name.includes('shadow') ? 'shadow'
      : file.endsWith('typography.css') ? 'font' : 'other';
const tokens = tokenFiles.flatMap((f) =>
  [...readFileSync(join(root, f), 'utf8').matchAll(/^\s*(--[\w-]+)\s*:\s*([^;]+);/gm)].map((m) => ({
    name: m[1], value: m[2].trim().replace(/\s*\/\*.*$/, ''), kind: kindOf(m[1], f), definedIn: f,
  })),
);

const manifest = {
  namespace: NAMESPACE,
  components,
  startingPoints: [],
  cards,
  templates: [],
  hasThumbnailHtml: existsSync(join(root, 'thumbnail.html')),
  globalCssPaths: ['tokens/fonts.css', ...tokenFiles, 'components/components.css', 'styles.css'],
  tokens,
  themes: [],
  fonts: [],
  brandFonts: [
    { family: 'Anton', tokens: ['--font-display'], path: 'tokens/fonts.css' },
    { family: 'Archivo', tokens: ['--font-body'], path: 'tokens/fonts.css' },
  ],
};
writeFileSync(join(root, '_ds_manifest.json'), JSON.stringify(manifest));
console.log(`bundle: ${components.length} components; manifest: ${cards.length} cards, ${tokens.length} tokens`);
